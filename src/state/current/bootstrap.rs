pub(super) fn bootstrap_open_ready(lease: BootstrapLease) -> Result<CurrentState, StateError> {
    lease.revalidate()?;
    let root = lease.held_root_path();
    validate_current_root_entries(&root)?;
    let database_path = lease.artifact_path("host.sqlite");
    let metadata =
        exact_artifact_metadata(&database_path)?.ok_or(StateError::BootstrapArtifactMismatch)?;
    let expected = BootstrapFileIdentity {
        device: lease
            .record
            .database_device
            .ok_or(StateError::InvalidBootstrapLock)?,
        inode: lease
            .record
            .database_inode
            .ok_or(StateError::InvalidBootstrapLock)?,
    };
    if !metadata.is_file()
        || !is_private_owner_file(&metadata)
        || bootstrap_file_identity(&metadata) != expected
    {
        return Err(StateError::BootstrapArtifactMismatch);
    }
    let provisional_expected = BootstrapFileIdentity {
        device: lease
            .record
            .provisional_device
            .ok_or(StateError::InvalidBootstrapLock)?,
        inode: lease
            .record
            .provisional_inode
            .ok_or(StateError::InvalidBootstrapLock)?,
    };
    let identity = read_raw_schema_identity(&database_path)?;
    ensure_current_raw_identity(identity)?;
    ensure_no_staging_database(&root)?;
    reject_current_epoch_artifacts(&root)?;
    let database = open_bootstrap_database(&lease, "host.sqlite", &database_path, expected)?;
    configure_current_connection(&database.connection)?;
    validate_schema15(&database.connection)?;
    let lease_generation =
        validate_ready_database_metadata(&database.connection, &lease, provisional_expected)?;
    let expected_contents = provisional_lock_contents(&lease.record.host_id, lease_generation)?;
    let provisional_path = lease.artifact_path(PROVISIONAL_LOCK_FILE);
    let provisional_file = open_private_provisional_file_at(
        &lease.root_directory,
        PROVISIONAL_LOCK_FILE,
        &provisional_path,
        false,
    )?;
    let opened_provisional_identity =
        validate_provisional_lock_file(&provisional_file, &provisional_path, &expected_contents)?;
    if opened_provisional_identity.device != provisional_expected.device
        || opened_provisional_identity.inode != provisional_expected.inode
    {
        return Err(StateError::BootstrapArtifactMismatch);
    }
    drop(provisional_file);
    let HeldBootstrapDatabase { connection, file } = database;
    drop(file);
    lease.revalidate()?;
    let state_root = lease.root.clone();
    drop(lease);
    Ok(CurrentState {
        connection,
        root: state_root,
        mode: StateMode::Current,
    })
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct RawSchemaIdentity {
    application_id: u32,
    user_version: i64,
}

fn read_raw_schema_identity(path: &Path) -> Result<RawSchemaIdentity, StateError> {
    let metadata = exact_artifact_metadata(path)?.ok_or(StateError::MalformedHostSchema)?;
    if !metadata.is_file() || !is_private_owner_file(&metadata) {
        return Err(StateError::MalformedHostSchema);
    }
    let mut options = OpenOptions::new();
    options.read(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.custom_flags(nix::libc::O_CLOEXEC | nix::libc::O_NOFOLLOW);
    }
    let mut file = options
        .open(path)
        .map_err(|error| StateError::io(path, error))?;
    let opened_metadata = file
        .metadata()
        .map_err(|error| StateError::io(path, error))?;
    if !opened_metadata.is_file()
        || !is_private_owner_file(&opened_metadata)
        || bootstrap_file_identity(&opened_metadata) != bootstrap_file_identity(&metadata)
    {
        return Err(StateError::MalformedHostSchema);
    }
    let mut header = Vec::new();
    std::io::Read::by_ref(&mut file)
        .take(101)
        .read_to_end(&mut header)
        .map_err(|error| StateError::io(path, error))?;
    if header.len() < 72 || &header[..16] != b"SQLite format 3\0" {
        return Err(StateError::MalformedHostSchema);
    }
    let user_version = i64::from(u32::from_be_bytes(
        header[60..64]
            .try_into()
            .map_err(|_| StateError::MalformedHostSchema)?,
    ));
    let application_id = u32::from_be_bytes(
        header[68..72]
            .try_into()
            .map_err(|_| StateError::MalformedHostSchema)?,
    );
    Ok(RawSchemaIdentity {
        application_id,
        user_version,
    })
}

/// Opens a current database relative to the held bootstrap root, validates
/// the opened descriptor against the visible path and lock identity, and only
/// then asks `SQLite` to open the already-held file through `/proc/self/fd`.
/// `SQLITE_OPEN_NOFOLLOW` is intentionally omitted for that final open: the
/// descriptor link is the authority, while the initial `openat` above is
/// no-follow and root-anchored.
pub(super) fn open_bootstrap_database(
    lease: &BootstrapLease,
    name: &str,
    path: &Path,
    expected: BootstrapFileIdentity,
) -> Result<HeldBootstrapDatabase, StateError> {
    let visible = exact_artifact_metadata(path)?.ok_or(StateError::BootstrapArtifactMismatch)?;
    if !visible.is_file()
        || !is_private_owner_file(&visible)
        || bootstrap_file_identity(&visible) != expected
    {
        return Err(StateError::BootstrapArtifactMismatch);
    }
    ensure_database_sidecars_absent(path)?;
    let file = open_bootstrap_relative_file(&lease.root_directory, name, path, false).map_err(
        |error| match error {
            StateError::Io { .. } => StateError::BootstrapArtifactMismatch,
            other => other,
        },
    )?;
    validate_held_bootstrap_database_file(&file, path, expected)?;
    let sqlite_path = sqlite_held_file_path(&file)?;
    let connection = Connection::open_with_flags(
        &sqlite_path,
        OpenFlags::SQLITE_OPEN_READ_WRITE | OpenFlags::SQLITE_OPEN_NO_MUTEX,
    )
    .map_err(StateError::Sqlite)?;
    let database = HeldBootstrapDatabase { connection, file };
    validate_held_bootstrap_database_file(&database.file, path, expected)?;
    ensure_database_sidecars_absent(path)?;
    Ok(database)
}

pub(super) fn validate_held_bootstrap_database_file(
    file: &File,
    path: &Path,
    expected: BootstrapFileIdentity,
) -> Result<(), StateError> {
    let opened = file
        .metadata()
        .map_err(|error| StateError::io(path, error))?;
    let visible = exact_artifact_metadata(path)?.ok_or(StateError::BootstrapArtifactMismatch)?;
    if !opened.is_file()
        || !is_private_owner_file(&opened)
        || !visible.is_file()
        || !is_private_owner_file(&visible)
        || bootstrap_file_identity(&opened) != expected
        || bootstrap_file_identity(&visible) != expected
        || bootstrap_file_identity(&opened) != bootstrap_file_identity(&visible)
    {
        return Err(StateError::BootstrapArtifactMismatch);
    }
    Ok(())
}

pub(super) fn sqlite_held_file_path(file: &File) -> Result<PathBuf, StateError> {
    #[cfg(target_os = "linux")]
    {
        let proc_fd = Path::new("/proc/self/fd");
        if !proc_fd.is_dir() {
            return Err(StateError::InvalidBootstrapLock);
        }
        Ok(proc_fd.join(file.as_raw_fd().to_string()))
    }
    #[cfg(not(target_os = "linux"))]
    {
        let _ = file;
        Err(StateError::InvalidBootstrapLock)
    }
}

fn ensure_current_raw_identity(identity: RawSchemaIdentity) -> Result<(), StateError> {
    if identity.user_version < HOST_SCHEMA_VERSION {
        return Err(StateError::HostStateResetRequired(identity.user_version));
    }
    if identity.user_version > HOST_SCHEMA_VERSION {
        return Err(StateError::UnsupportedFutureHostSchema(
            identity.user_version,
        ));
    }
    if identity.application_id != HOST_APPLICATION_ID {
        return Err(StateError::MalformedHostSchema);
    }
    Ok(())
}

pub(super) fn open_bootstrap_relative_file(
    root_directory: &File,
    name: &str,
    path: &Path,
    create_new: bool,
) -> Result<File, StateError> {
    #[cfg(unix)]
    {
        use nix::fcntl::{OFlag, openat};
        use nix::sys::stat::Mode;
        let mut flags = OFlag::O_RDWR | OFlag::O_CLOEXEC | OFlag::O_NOFOLLOW;
        if create_new {
            flags |= OFlag::O_CREAT | OFlag::O_EXCL;
        }
        let descriptor = openat(root_directory, name, flags, Mode::from_bits_truncate(0o600))
            .map_err(|error| {
                StateError::io(path, std::io::Error::from_raw_os_error(error as i32))
            })?;
        Ok(File::from(descriptor))
    }
    #[cfg(not(unix))]
    {
        let _ = (root_directory, name, create_new);
        Err(StateError::InvalidBootstrapLock)
    }
}

pub(super) fn open_private_bootstrap_file_at(
    root_directory: &File,
    name: &str,
    path: &Path,
    create_new: bool,
) -> Result<File, StateError> {
    let before = exact_artifact_metadata(path)?;
    if let Some(metadata) = &before
        && (!metadata.is_file() || !is_private_owner_file(metadata))
    {
        return Err(StateError::InvalidBootstrapLock);
    }
    let file = open_bootstrap_relative_file(root_directory, name, path, create_new)?;
    let opened = file
        .metadata()
        .map_err(|error| StateError::io(path, error))?;
    if !opened.is_file()
        || !is_current_owner(&opened)
        || before.is_some_and(|metadata| {
            bootstrap_file_identity(&metadata) != bootstrap_file_identity(&opened)
        })
    {
        return Err(StateError::InvalidBootstrapLock);
    }
    set_private_file_permissions_handle(&file, path)?;
    let private = file
        .metadata()
        .map_err(|error| StateError::io(path, error))?;
    if !private.is_file() || !is_private_owner_file(&private) {
        return Err(StateError::InvalidBootstrapLock);
    }
    Ok(file)
}

pub(super) fn reject_current_epoch_artifacts(root: &Path) -> Result<(), StateError> {
    for name in [
        "client.sqlite",
        "client.sqlite-wal",
        "client.sqlite-shm",
        "transition.lock",
    ] {
        if exact_artifact_metadata(&root.join(name))?.is_some() {
            return Err(StateError::StateRecoveryRequired(
                StateRecoveryReason::UnknownFreshRootArtifact,
            ));
        }
    }
    Ok(())
}

pub(super) fn ensure_no_staging_database(root: &Path) -> Result<(), StateError> {
    for entry in fs::read_dir(root).map_err(|error| StateError::io(root, error))? {
        let entry = entry.map_err(|error| StateError::io(root, error))?;
        if entry
            .file_name()
            .to_str()
            .is_some_and(|name| name.starts_with(BOOTSTRAP_STAGE_PREFIX))
        {
            return Err(StateError::BootstrapArtifactMismatch);
        }
    }
    Ok(())
}

pub(super) fn ensure_bootstrap_path_absent(root: &Path, name: &str) -> Result<(), StateError> {
    if exact_artifact_metadata(&root.join(name))?.is_some() {
        return Err(StateError::BootstrapEffectUnknown);
    }
    Ok(())
}

pub(super) fn validate_current_root_entries(root: &Path) -> Result<(), StateError> {
    let mut count = 0_u16;
    for entry in fs::read_dir(root).map_err(|error| StateError::io(root, error))? {
        let entry = entry.map_err(|error| StateError::io(root, error))?;
        count = count.saturating_add(1);
        if count > 256 {
            return Err(StateError::FreshRootRejected(
                FreshRootRejection::UnknownArtifact,
            ));
        }
        let name = entry
            .file_name()
            .into_string()
            .map_err(|_| StateError::FreshRootRejected(FreshRootRejection::UnknownArtifact))?;
        if name == BOOTSTRAP_LOCK_FILE
            || name == "host.sqlite"
            || name == PROVISIONAL_LOCK_FILE
            || name == "run"
            || name == "presentation"
            || name.starts_with(BOOTSTRAP_STAGE_PREFIX)
        {
            continue;
        }
        return Err(
            if is_retired_client_artifact(&name) || name == "transition.lock" {
                StateError::StateRecoveryRequired(StateRecoveryReason::UnknownFreshRootArtifact)
            } else {
                StateError::FreshRootRejected(FreshRootRejection::UnknownArtifact)
            },
        );
    }
    Ok(())
}

pub(super) fn ensure_database_sidecars_absent(path: &Path) -> Result<(), StateError> {
    let file_name = path
        .file_name()
        .and_then(|name| name.to_str())
        .ok_or(StateError::BootstrapArtifactMismatch)?;
    for suffix in ["-wal", "-shm", "-journal"] {
        if exact_artifact_metadata(&path.with_file_name(format!("{file_name}{suffix}")))?.is_some()
        {
            return Err(StateError::BootstrapEffectUnknown);
        }
    }
    Ok(())
}

pub(super) fn ensure_named_stage_absent(
    root: &Path,
    expected: Option<&str>,
) -> Result<(), StateError> {
    for entry in fs::read_dir(root).map_err(|error| StateError::io(root, error))? {
        let entry = entry.map_err(|error| StateError::io(root, error))?;
        let Some(name) = entry.file_name().to_str().map(ToOwned::to_owned) else {
            continue;
        };
        if name.starts_with(BOOTSTRAP_STAGE_PREFIX) && expected != Some(name.as_str()) {
            return Err(StateError::BootstrapEffectUnknown);
        }
    }
    Ok(())
}

pub(super) fn create_private_fresh_root(path: &Path) -> Result<(), StateError> {
    fs::create_dir(path).map_err(|error| StateError::io(path, error))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::{OpenOptionsExt, PermissionsExt};
        let mut options = OpenOptions::new();
        options.read(true);
        options.custom_flags(nix::libc::O_CLOEXEC | nix::libc::O_NOFOLLOW);
        let directory = options
            .open(path)
            .map_err(|error| StateError::io(path, error))?;
        let before = directory
            .metadata()
            .map_err(|error| StateError::io(path, error))?;
        if !before.is_dir() || !is_current_owner(&before) {
            return Err(StateError::FreshRootRejected(
                FreshRootRejection::NonPrivateDirectory,
            ));
        }
        directory
            .set_permissions(fs::Permissions::from_mode(0o700))
            .map_err(|error| StateError::io(path, error))?;
        let after = directory
            .metadata()
            .map_err(|error| StateError::io(path, error))?;
        if !after.is_dir()
            || !is_private_owner_directory(&after)
            || file_identity(&before) != file_identity(&after)
        {
            return Err(StateError::FreshRootRejected(
                FreshRootRejection::NonPrivateDirectory,
            ));
        }
    }
    #[cfg(not(unix))]
    {
        super::super::utils::set_private_directory_permissions(path)?;
    }
    if let Some(parent) = path.parent() {
        sync_directory(parent)?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    #[cfg(target_os = "linux")]
    #[test]
    fn held_database_identity_rejects_visible_replacement() {
        use std::{fs, os::unix::fs::PermissionsExt};

        let temporary = tempfile::tempdir().unwrap();
        let root = temporary.path().join("state");
        let generator = crate::domain::RandomIdGenerator;
        drop(super::create_current(&root, &generator).unwrap());
        let root_directory = super::open_bootstrap_root_directory(&root).unwrap();
        let path = super::bootstrap_root_artifact_path(&root, &root_directory, "host.sqlite");
        let metadata = super::exact_artifact_metadata(&path).unwrap().unwrap();
        let expected = super::bootstrap_file_identity(&metadata);
        let file =
            super::open_bootstrap_relative_file(&root_directory, "host.sqlite", &path, false)
                .unwrap();

        let moved = temporary.path().join("host.sqlite.moved");
        fs::rename(root.join("host.sqlite"), &moved).unwrap();
        fs::copy(&moved, root.join("host.sqlite")).unwrap();
        fs::set_permissions(root.join("host.sqlite"), fs::Permissions::from_mode(0o600)).unwrap();

        assert!(matches!(
            super::validate_held_bootstrap_database_file(&file, &path, expected),
            Err(crate::state::StateError::BootstrapArtifactMismatch)
        ));
        assert!(moved.is_file());
    }
}
